#!/usr/bin/env bash
# Publishes UI test results (screenshots, report.md, logcat) to the dedicated
# `ui-test-results` branch so people and AI assistants can view them directly on
# GitHub (report.md renders with inline screenshots) without downloading a ZIP.
# Usage: publish-results.sh <results-dir> <run-folder-name>
# Prints the published folder path on success. Never force-pushes.
set -euo pipefail

SRC="$(cd "$1" && pwd)"
RUN_NAME="$2"
BRANCH="${UI_RESULTS_BRANCH:-ui-test-results}"
KEEP="${UI_RESULTS_KEEP:-40}"
WORK="$(mktemp -d)"

git config --global user.name "github-actions[bot]"
git config --global user.email "41898282+github-actions[bot]@users.noreply.github.com"

REMOTE="$(git remote get-url origin)"
# Reuse the checkout's auth header (actions/checkout persists it in local config).
AUTH="$(git config --local --get http.https://github.com/.extraheader || true)"

apply_results() {
  local repo="$1"
  rm -rf "$repo"
  if git ls-remote --exit-code --heads origin "$BRANCH" >/dev/null 2>&1; then
    git ${AUTH:+-c "http.https://github.com/.extraheader=$AUTH"} clone --quiet --depth 1 --branch "$BRANCH" --single-branch "$REMOTE" "$repo"
  else
    git init --quiet "$repo"
    git -C "$repo" checkout --quiet --orphan "$BRANCH"
    git -C "$repo" remote add origin "$REMOTE"
  fi
  [[ -n "$AUTH" ]] && git -C "$repo" config http.https://github.com/.extraheader "$AUTH"
  (
    cd "$repo"
    DEST="runs/$RUN_NAME"
    rm -rf "$DEST"
    mkdir -p "$DEST"
    cp -a "$SRC/." "$DEST/"
    rm -rf "$DEST/.apk"

    # Pointer to the newest run per app.
    mkdir -p latest
    for app_dir in "$DEST"/*/; do
      [[ -d "$app_dir" ]] || continue
      app="$(basename "$app_dir")"
      {
        echo "# Latest UI test: $app"
        echo
        echo "Run: [$RUN_NAME](../$DEST/summary.md)"
        echo
        for rep in "$app_dir"*/report.md; do
          [[ -f "$rep" ]] || continue
          echo "- [$(basename "$(dirname "$rep")")](../$rep)"
        done
      } > "latest/$app.md"
    done

    # Keep the branch small: retain only the newest $KEEP runs.
    ls -1 runs | sort -t- -k1,1n | head -n -"$KEEP" | while read -r old; do
      [[ -n "$old" ]] && rm -rf "runs/$old"
    done

    {
      echo "# UI test results"
      echo
      echo "Generated by \`.github/workflows/ui-test-apk.yml\`. Newest runs first."
      echo
      echo "## Latest per app"
      for f in latest/*.md; do [[ -f "$f" ]] && echo "- [$(basename "$f" .md)]($f)"; done
      echo
      echo "## Runs"
      ls -1 runs | sort -t- -k1,1nr | while read -r r; do echo "- [$r](runs/$r/summary.md)"; done
    } > README.md

    git add -A
    git commit --quiet -m "UI test results: $RUN_NAME"
  )
}

for attempt in 1 2 3 4 5; do
  apply_results "$WORK/repo"
  if git -C "$WORK/repo" push --quiet origin "HEAD:$BRANCH"; then
    echo "runs/$RUN_NAME"
    exit 0
  fi
  echo "Push rejected (attempt $attempt); retrying on a fresh copy of $BRANCH" >&2
  sleep $((attempt * 3))
done
echo "::error::Could not push UI test results to $BRANCH" >&2
exit 1
